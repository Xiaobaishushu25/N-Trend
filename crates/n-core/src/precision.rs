/// 品种默认乘数：优先按品种中文名匹配，其次按代码前缀（大写），未收录兜底 10.0。
pub fn default_multiplier(code: &str, variety: &str) -> f64 {
    if !variety.is_empty() {
        if let Some((_, mult)) = DEFAULT_MULTIPLIERS.iter().find(|(name, _)| *name == variety) {
            return *mult;
        }
    }
    let prefix = code_prefix(code).to_ascii_uppercase();
    DEFAULT_MULTIPLIERS
        .iter()
        .find(|(name, _)| name.to_ascii_uppercase() == prefix)
        .map(|(_, mult)| *mult)
        .unwrap_or(10.0)
}

/// 获取品种乘数
pub fn effective_multiplier(code: &str, variety: &str) -> f64 {
    default_multiplier(code, variety)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_by_variety_and_prefix() {
        assert_eq!(default_tick("RB2501", "螺纹钢"), 1.0);
        assert_eq!(default_tick("AU0", ""), 0.02);
        assert_eq!(default_tick("CU0", "沪铜"), 10.0);
        assert_eq!(default_tick("I0", ""), 0.5);
        assert_eq!(default_tick("IF0", ""), 0.2);
        assert_eq!(default_tick("XX9999", "未知品种"), 1.0);
    }

    #[test]
    fn matches_multiplier_correctly() {
        assert_eq!(effective_multiplier("RB2501", "螺纹钢"), 10.0);
        assert_eq!(effective_multiplier("CF0", "棉花连续"), 5.0);
        assert_eq!(effective_multiplier("I0", "铁矿石"), 100.0);
        assert_eq!(effective_multiplier("AU0", "沪金"), 1000.0);
        assert_eq!(effective_multiplier("SA0", "纯碱"), 20.0);
        assert_eq!(effective_multiplier("IF0", ""), 300.0);
    }

    #[test]
    fn effective_tick_prefers_explicit() {
        assert_eq!(effective_tick(2.0, "RB0", "螺纹钢"), 2.0);
        assert_eq!(effective_tick(0.0, "AU0", "黄金"), 0.02);
        assert_eq!(effective_tick(0.0, "RB0", ""), 1.0);
    }
}
