/// 合约代码的字母前缀（数字前的部分，如 RB0 → RB、MA0 → MA、I0 → I）。
fn code_prefix(code: &str) -> &str {
    let end = code
        .find(|c: char| c.is_ascii_digit())
        .unwrap_or(code.len());
    &code[..end]
}

/// 品种默认 tick：优先按品种中文名匹配，其次按代码前缀，未收录兜底 1.0。
pub fn default_tick(code: &str, variety: &str) -> f64 {
    if let Some((_, tick)) = DEFAULT_TICKS.iter().find(|(name, _)| *name == variety) {
        return *tick;
    }
    let prefix = code_prefix(code);
    DEFAULT_TICKS
        .iter()
        .find(|(name, _)| *name == prefix)
        .map(|(_, tick)| *tick)
        .unwrap_or(1.0)
}

/// 行内有效 tick：显式设置（>0）优先，否则用内置默认。
pub fn effective_tick(tick_size: f64, code: &str, variety: &str) -> f64 {
    if tick_size > 0.0 {
        tick_size
    } else {
        default_tick(code, variety)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_by_variety_and_prefix() {
        assert_eq!(default_tick("RB2501", "螺纹钢"), 1.0);
        assert_eq!(default_tick("AU0", ""), 0.02);
        assert_eq!(default_tick("CU0", "沪铜"), 10.0);
        assert_eq!(default_tick("I0", ""), 0.5);
        assert_eq!(default_tick("IF0", ""), 0.2);
        assert_eq!(default_tick("XX9999", "未知品种"), 1.0);
    }

    #[test]
    fn effective_tick_prefers_explicit() {
        assert_eq!(effective_tick(2.0, "RB0", "螺纹钢"), 2.0);
        assert_eq!(effective_tick(0.0, "AU0", "黄金"), 0.02);
        assert_eq!(effective_tick(0.0, "RB0", ""), 1.0);
    }
}
