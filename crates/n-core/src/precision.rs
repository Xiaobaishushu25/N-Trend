/// 合约代码的字母前缀（数字前的部分，如 RB0 → RB、MA0 → MA、I0 → I）。
fn code_prefix(code: &str) -> &str {
    let end = code
        .find(|c: char| c.is_ascii_digit())
        .unwrap_or(code.len());
    &code[..end]
}

/// 品种默认 tick：优先按品种中文名匹配，其次按代码前缀，未收录兜底 1.0。
pub fn default_tick(code: &str, variety: &str) -> f64 {
    if let Some((_, tick)) = DEFAULT_TICKS.iter().find(|(name, _)| *name == variety) {
        return *tick;
    }
    let prefix = code_prefix(code);
    DEFAULT_TICKS
        .iter()
        .find(|(name, _)| *name == prefix)
        .map(|(_, tick)| *tick)
        .unwrap_or(1.0)
}

/// 行内有效 tick：显式设置（>0）优先，否则用内置默认。
pub fn effective_tick(tick_size: f64, code: &str, variety: &str) -> f64 {
    if tick_size > 0.0 {
        tick_size
    } else {
        default_tick(code, variety)
    }
}

