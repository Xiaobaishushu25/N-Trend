/**
 * 国内期货全市场交易时段与开盘检测工具
 */

/**
 * 判断当前时刻是否处于国内期货全市场交易时段（或临近开盘的竞价/恢复检测窗口）。
 * 覆盖国内全部期货品种（含日盘及夜盘至 23:00、23:30、01:00、02:30 的全部品种）。
 *
 * 时段规则：
 * - 周日：全天休市（无夜盘）
 * - 周六：00:00 - 02:32 为周五夜盘延续；02:32 之后全天休市
 * - 周一：08:55 之前休市（周日晚无夜盘）；08:55 之后按正常交易日时段
 * - 周一至周五工作日：
 *   - 跨日凌晨时段：00:00 - 02:32（夜盘延续，周二至周六）
 *   - 日盘上午小节 1：08:55 - 10:17（含 08:55 集合竞价与 2 分钟收盘缓冲）
 *   - 日盘上午小节 2：10:28 - 11:32（10:15~10:28 茶歇后预热至收盘缓冲）
 *   - 日盘下午小节：13:28 - 15:05（11:30~13:28 午休后预热至收盘结算缓冲）
 *   - 夜盘前半夜：20:55 - 24:00（20:55 集合竞价临近开盘即恢复活跃检测）
 * 其余时间（如 10:17~10:28、11:32~13:28、15:05~20:55 等）均为休市结算期。
 */
export function isMarketTradingWindow(date: Date = new Date()): boolean {
  const day = date.getDay() // 0=周日, 1=周一, ..., 6=周六
  const mins = date.getHours() * 60 + date.getMinutes()

  // 1. 周日全天休市，当晚无夜盘
  if (day === 0) return false

  // 2. 周六仅在 02:32 前为周五跨日夜盘延续，之后全天休市
  if (day === 6) {
    return mins <= 2 * 60 + 32
  }

  // 3. 周一凌晨无夜盘（周日晚不开盘），08:55 集合竞价之前均为休市
  if (day === 1 && mins < 8 * 60 + 55) {
    return false
  }

  // 4. 周二至周五凌晨 00:00 - 02:32 为前一晚夜盘延续时段
  if (day >= 2 && day <= 5 && mins <= 2 * 60 + 32) {
    return true
  }

  // 5. 工作日正常日盘时段
  // 上午第 1 小节（08:55 集合竞价 - 10:15，宽限至 10:17）
  if (mins >= 8 * 60 + 55 && mins <= 10 * 60 + 17) {
    return true
  }

  // 上午第 2 小节（10:28 提前预热 - 11:30，宽限至 11:32）
  if (mins >= 10 * 60 + 28 && mins <= 11 * 60 + 32) {
    return true
  }

  // 下午盘（13:28 提前预热 - 15:00，结算宽限至 15:05）
  if (mins >= 13 * 60 + 28 && mins <= 15 * 60 + 5) {
    return true
  }

  // 6. 夜盘前半夜（周一至周五，20:55 集合竞价临近开盘 - 24:00）
  if (mins >= 20 * 60 + 55) {
    return true
  }

  return false
}
